"""Convert the address-annotated ROM listing into a C ROM loader.

Usage: python3 tools/asm2c.py [--input resource/disas.asm] [--output build/rom.c]
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORD_LINE = re.compile(
    r";\s*([0-9A-Fa-f]{4,5})\s*\|\s*((?:[0-9A-Fa-f]{4}(?:\s+|$))+)$"
)


def parse_listing(path):
    words = {}
    with open(path, encoding="ascii") as listing:
        for line_number, line in enumerate(listing, 1):
            match = WORD_LINE.search(line.rstrip())
            if not match:
                continue
            address = int(match.group(1), 16)
            for index, token in enumerate(match.group(2).split()):
                word_address = address + index * 2
                word = int(token, 16)
                previous = words.get(word_address)
                if previous is not None and previous != word:
                    raise ValueError(
                        "%s:%d: conflicting word at %05X" %
                        (path, line_number, word_address)
                    )
                words[word_address] = word

    if not words:
        raise ValueError("no address-annotated words found in %s" % path)
    if min(words) != 0 or max(words) % 2:
        raise ValueError("listing must cover an even-addressed ROM starting at 00000")

    rom_size = max(words) + 2
    missing = [address for address in range(0, rom_size, 2) if address not in words]
    if missing:
        raise ValueError("listing has %d missing words; first at %05X" %
                         (len(missing), missing[0]))

    rom = bytearray(rom_size)
    for address, word in words.items():
        rom[address] = word & 0xFF
        rom[address + 1] = word >> 8
    return rom


def write_c(rom, path):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as output:
        output.write("/* Generated by tools/asm2c.py. Do not edit. */\n")
        output.write('#include "../emu/nx8.h"\n\n')
        output.write("static const uint8_t fx580vnx_rom[] = {\n")
        for offset in range(0, len(rom), 12):
            values = ", ".join("0x%02X" % value for value in rom[offset:offset + 12])
            output.write("    " + values + ",\n")
        output.write("};\n\n")
        output.write("void fx580vnx_load_rom(Nx8Machine *machine)\n")
        output.write("{\n")
        output.write("    nx8_load_rom(machine, fx580vnx_rom, sizeof(fx580vnx_rom));\n")
        output.write("}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default=os.path.join(ROOT, "resource", "disas.asm"))
    parser.add_argument("--output", default=os.path.join(ROOT, "build", "rom.c"))
    args = parser.parse_args()

    rom = parse_listing(args.input)
    write_c(rom, args.output)
    print("wrote %s (%d bytes from %s)" % (args.output, len(rom), args.input))


if __name__ == "__main__":
    main()